#!/usr/bin/env python3
"""Drive scripts/enable_hooks.py against throwaway clones, with stubs standing in for each framework.

Every case builds its own repository under a temporary directory and runs the script there with
its interpreter. PATH holds only the stubs and Git, so no real `pre-commit` or `dotnet` is reached.
Git reads an empty global config and no system config, so the host's own settings cannot leak in.
A stub records each call it takes, which is how a case tells a step that ran from one skipped.
"""

from __future__ import annotations

import contextlib
import hashlib
import importlib.util
import json
import os
import shutil
import signal
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path
from types import FrameType

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "scripts" / "enable_hooks.py"
sys.path.insert(0, str(ROOT / "spec"))
import git_env
from test_pre_commit_hook import assert_group_ended, end_group, wait_until_started

RECORD = """\
import os
import sys
with open(os.environ["STUB_CALLS"], "a", encoding="utf-8") as calls:
    calls.write(" ".join([os.environ["STUB_NAME"], *sys.argv[1:]]) + "\\n")
"""

PRE_COMMIT_INSTALL = (
    RECORD
    + """\
from pathlib import Path
hook = Path(".git", "hooks", "pre-commit")
hook.parent.mkdir(parents=True, exist_ok=True)
hook.write_text("#!/usr/bin/env bash\\n# File generated by pre-commit: https://pre-commit.com\\n")
hook.chmod(0o755)
"""
)

DOTNET = (
    RECORD
    + """\
import subprocess
from pathlib import Path
if sys.argv[1:] == os.environ.get("STUB_FAIL", "").split():
    sys.exit(3)
if sys.argv[1:] == ["husky", "install"]:
    subprocess.run(["git", "config", "core.hooksPath", ".husky"], check=True)
    runtime = Path(".husky", "_", "husky.sh")
    runtime.parent.mkdir(parents=True, exist_ok=True)
    runtime.write_text("#!/usr/bin/env sh\\n")
"""
)

BLOCK = (
    RECORD
    + """\
import time
open(os.environ["STUB_READY"], "w").close()
time.sleep(600)
"""
)

RESET_SIGINT = (
    "import os, signal, sys; signal.signal(signal.SIGINT, signal.SIG_DFL);"
    " os.execv(sys.executable, [sys.executable, sys.argv[1]])"
)

MANIFEST = {"version": 1, "isRoot": True, "tools": {"husky": {"version": "0.7.2"}}}


def snapshot(root: Path) -> dict[str, tuple[int, str]]:
    """Every path under `root`, `.git` included, with its modification time and content digest."""
    state: dict[str, tuple[int, str]] = {}
    for directory, dirs, files in os.walk(root):
        for name in dirs + files:
            path = Path(directory, name)
            digest = hashlib.sha256(path.read_bytes()).hexdigest() if path.is_file() else "dir"
            state[str(path.relative_to(root))] = (path.stat().st_mtime_ns, digest)
    return state


class EnableHooksCase(unittest.TestCase):
    """One standalone clone, an isolated Git config, and a PATH holding only stubs and Git."""

    def setUp(self) -> None:
        real_git = shutil.which("git")
        if real_git is None:
            raise AssertionError("git must be on PATH")
        self.root = Path(self.enterContext(tempfile.TemporaryDirectory())).resolve()
        self.stubs = self.root / "bin"
        self.stubs.mkdir()
        self.calls = self.root / "calls.txt"
        global_config = self.root / "gitconfig"
        global_config.write_text("", encoding="utf-8")
        if os.name == "nt":
            path = os.pathsep.join([str(self.stubs), str(Path(real_git).parent)])
        else:
            (self.stubs / "git").symlink_to(real_git)
            path = str(self.stubs)
        self.env = git_env.without_git_location()
        self.env.update(
            {
                "PATH": path,
                "GIT_CONFIG_GLOBAL": str(global_config),
                "GIT_CONFIG_NOSYSTEM": "1",
                "GIT_CEILING_DIRECTORIES": str(self.root),
                "STUB_CALLS": str(self.calls),
            }
        )
        self.env["PYTHONIOENCODING"] = "utf-8"
        self.clone = self.root / "clone"
        self.clone.mkdir()
        self.git(self.clone, "init", "-q")

    def git(self, cwd: Path, *args: str) -> str:
        result = subprocess.run(
            ["git", *args],
            cwd=cwd,
            env=self.env,
            capture_output=True,
            text=True,
            encoding="utf-8",
            check=True,
        )
        return result.stdout.strip()

    def hooks_path(self) -> str:
        result = subprocess.run(
            ["git", "config", "--get", "core.hooksPath"],
            cwd=self.clone,
            env=self.env,
            capture_output=True,
            text=True,
            encoding="utf-8",
            check=False,
        )
        return result.stdout.strip()

    def stub(self, name: str, body: str) -> None:
        """Put a command named `name` on PATH that runs the Python `body` with this interpreter."""
        source = self.stubs / f"{name}_stub.py"
        source.write_text(f"import os\nos.environ['STUB_NAME'] = {name!r}\n{body}", "utf-8")
        if os.name == "nt":
            launcher = self.stubs / f"{name}.cmd"
            launcher.write_text(f'@"{sys.executable}" "{source}" %*\r\n', encoding="utf-8")
        else:
            launcher = self.stubs / name
            launcher.write_text(f'#!/bin/sh\nexec "{sys.executable}" "{source}" "$@"\n', "utf-8")
            launcher.chmod(0o755)

    def recorded(self) -> list[str]:
        if not self.calls.exists():
            return []
        return self.calls.read_text(encoding="utf-8").splitlines()

    def run_script(self, *args: str, cwd: Path | None = None) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [sys.executable, str(SCRIPT), *args],
            cwd=cwd or self.clone,
            env=self.env,
            capture_output=True,
            text=True,
            encoding="utf-8",
            timeout=120,
            check=False,
        )

    def write(self, relative: str, text: str = "#!/bin/sh\nexit 0\n") -> Path:
        path = self.clone / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        return path

    def assert_rerun_writes_nothing(self) -> None:
        before, calls = snapshot(self.clone), self.recorded()
        result = self.run_script()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("unchanged:", result.stdout)
        self.assertEqual(snapshot(self.clone), before)
        self.assertEqual(self.recorded(), calls)

    def assert_refused_unchanged(self, expected: str, cwd: Path | None = None) -> None:
        before = snapshot(self.clone)
        result = self.run_script(cwd=cwd)
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn(expected, result.stderr)
        self.assertNotIn("Traceback", result.stderr)
        self.assertEqual(snapshot(self.clone), before)
        self.assertEqual(self.recorded(), [])


class TestHusky(EnableHooksCase):
    def setUp(self) -> None:
        super().setUp()
        self.write(".husky/pre-commit")

    def test_it_sets_the_hooks_path_and_a_rerun_writes_nothing(self) -> None:
        result = self.run_script()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("changed: set core.hooksPath to .husky.", result.stdout)
        self.assertEqual(self.hooks_path(), ".husky")
        self.assert_rerun_writes_nothing()

    def test_another_spelling_of_the_same_directory_reads_as_enabled(self) -> None:
        self.git(self.clone, "config", "core.hooksPath", "./.husky/")
        self.assert_rerun_writes_nothing()

    def test_a_different_hooks_path_is_never_replaced(self) -> None:
        self.git(self.clone, "config", "core.hooksPath", "githooks")
        self.assert_refused_unchanged("core.hooksPath reads 'githooks'")

    def test_a_run_from_a_subdirectory_enables_the_top_level(self) -> None:
        subdirectory = self.clone / "docs"
        subdirectory.mkdir()
        result = self.run_script(cwd=subdirectory)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(self.hooks_path(), ".husky")

    def test_a_linked_worktree_is_refused_before_anything_is_written(self) -> None:
        identity = ("-c", "user.name=Example", "-c", "user.email=example@example.invalid")
        self.git(self.clone, "add", ".husky/pre-commit")
        self.git(self.clone, *identity, "commit", "-q", "--no-verify", "-m", "base")
        linked = self.root / "linked"
        self.git(self.clone, "worktree", "add", "-q", str(linked), "-b", "task")
        self.assert_refused_unchanged("is a linked worktree", cwd=linked)
        self.assertEqual(self.hooks_path(), "")


class TestHuskyNet(EnableHooksCase):
    def setUp(self) -> None:
        super().setUp()
        self.write(".husky/pre-commit")
        self.write(".config/dotnet-tools.json", json.dumps(MANIFEST))
        self.stub("dotnet", DOTNET)

    def test_it_restores_then_installs_and_a_rerun_writes_nothing(self) -> None:
        result = self.run_script()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(self.recorded(), ["dotnet tool restore", "dotnet husky install"])
        self.assertEqual(self.hooks_path(), ".husky")
        self.assertIn("changed:", result.stdout)
        self.assert_rerun_writes_nothing()

    def test_a_missing_runtime_is_installed_even_where_the_path_is_set(self) -> None:
        self.git(self.clone, "config", "core.hooksPath", ".husky")
        result = self.run_script()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(self.recorded(), ["dotnet tool restore", "dotnet husky install"])

    def test_a_failed_restore_stops_before_the_install(self) -> None:
        self.env["STUB_FAIL"] = "tool restore"
        result = self.run_script()
        self.assertEqual(result.returncode, 1, result.stdout)
        self.assertIn("dotnet tool restore exited 3", result.stderr)
        self.assertEqual(self.recorded(), ["dotnet tool restore"])
        self.assertEqual(self.hooks_path(), "")

    def test_a_different_hooks_path_is_never_replaced(self) -> None:
        self.git(self.clone, "config", "core.hooksPath", "githooks")
        self.assert_refused_unchanged("core.hooksPath reads 'githooks'")


class TestPreCommit(EnableHooksCase):
    def setUp(self) -> None:
        super().setUp()
        self.write(".pre-commit-config.yaml", "repos: []\n")
        self.hook = self.clone / ".git" / "hooks" / "pre-commit"

    def test_it_installs_once_and_a_rerun_writes_nothing(self) -> None:
        self.stub("pre-commit", PRE_COMMIT_INSTALL)
        result = self.run_script()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(self.recorded(), ["pre-commit install"])
        self.assertTrue(self.hook.is_file())
        self.assert_rerun_writes_nothing()

    def test_a_hook_it_did_not_write_is_never_replaced(self) -> None:
        self.stub("pre-commit", PRE_COMMIT_INSTALL)
        self.write(".git/hooks/pre-commit")
        self.assert_refused_unchanged("is a hook pre-commit did not write")

    def test_a_hook_quoting_the_header_mid_line_is_never_replaced(self) -> None:
        self.stub("pre-commit", PRE_COMMIT_INSTALL)
        self.write(".git/hooks/pre-commit", "#!/bin/sh\necho '# File generated by pre-commit'\n")
        self.assert_refused_unchanged("is a hook pre-commit did not write")

    def test_a_hooks_path_is_refused_rather_than_unset(self) -> None:
        self.stub("pre-commit", PRE_COMMIT_INSTALL)
        self.git(self.clone, "config", "core.hooksPath", ".githooks")
        self.assert_refused_unchanged("pre-commit installs no hook while it is set")

    def test_a_missing_pre_commit_names_the_install_step(self) -> None:
        self.assert_refused_unchanged("uv tool install pre-commit")

    def test_an_install_that_writes_no_hook_fails(self) -> None:
        self.stub("pre-commit", RECORD)
        result = self.run_script()
        self.assertEqual(result.returncode, 1, result.stdout)
        self.assertIn("left no hook of its own", result.stderr)


class TestRefusals(EnableHooksCase):
    def test_both_frameworks_are_refused(self) -> None:
        self.write(".husky/pre-commit")
        self.write(".pre-commit-config.yaml", "repos: []\n")
        self.assert_refused_unchanged("found both")

    def test_no_framework_is_refused(self) -> None:
        self.assert_refused_unchanged("found neither")

    def test_a_directory_outside_any_clone_is_refused(self) -> None:
        outside = self.root / "outside"
        outside.mkdir()
        result = self.run_script(cwd=outside)
        self.assertEqual(result.returncode, 1, result.stdout)
        self.assertIn("found no Git work tree here", result.stderr)

    def test_an_unknown_argument_is_refused_before_anything_is_read(self) -> None:
        self.write(".husky/pre-commit")
        before = snapshot(self.clone)
        result = self.run_script("--bogus-flag")
        self.assertEqual(result.returncode, 2)
        self.assertIn("unrecognized arguments: --bogus-flag", result.stderr)
        self.assertEqual(snapshot(self.clone), before)


@unittest.skipIf(os.name == "nt", "Windows delivers neither signal for a script to handle")
class TestInterrupt(EnableHooksCase):
    def test_a_signal_stops_the_step_and_ends_the_script_by_that_signal(self) -> None:
        """The script dies by the signal, and the step it started is gone with it.

        Standard error goes to a file rather than a pipe, so a surviving step cannot hold a read
        open. SIGINT is reset to its default in the child, since a runner started in the
        background ignores it and the child would inherit that.
        """
        self.write(".pre-commit-config.yaml", "repos: []\n")
        self.stub("pre-commit", BLOCK)
        for signum in (signal.SIGINT, signal.SIGTERM):
            with self.subTest(signal=signum.name):
                ready = self.root / f"ready-{signum.name}"
                self.env["STUB_READY"] = str(ready)
                with (self.root / f"stderr-{signum.name}").open("w+", encoding="utf-8") as err:
                    proc = subprocess.Popen(
                        [sys.executable, "-c", RESET_SIGINT, str(SCRIPT)],
                        cwd=self.clone,
                        env=self.env,
                        stdout=subprocess.DEVNULL,
                        stderr=err,
                        text=True,
                        encoding="utf-8",
                        start_new_session=True,
                    )
                    try:
                        wait_until_started(proc, ready)
                        proc.send_signal(signum)
                        proc.wait(timeout=60)
                        err.seek(0)
                        stderr = err.read()
                        self.assertEqual(proc.returncode, -signum, stderr)
                        self.assertIn(f"interrupted by {signum.name}.", stderr)
                        self.assertNotIn("Traceback", stderr)
                        assert_group_ended(proc.pid)
                        self.assertFalse((self.clone / ".git" / "hooks" / "pre-commit").exists())
                    finally:
                        end_group(proc)
                        with contextlib.suppress(ProcessLookupError):
                            os.killpg(proc.pid, signal.SIGKILL)

    def test_a_signal_handled_as_the_first_handler_starts_is_passed_over(self) -> None:
        """A SIGTERM handled as the SIGINT's handler starts leaves the SIGINT first.

        Python checks for signals as a function starts, so the pair can be handled there.
        A profile hook makes that nested call at that point, so the order is fixed, not raced.
        """
        spec = importlib.util.spec_from_file_location("enable_hooks_under_test", SCRIPT)
        assert spec is not None
        assert spec.loader is not None
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)

        def nest(frame: FrameType, event: str, _arg: object) -> None:
            if event == "call" and frame.f_code is module.on_signal.__code__:
                sys.setprofile(None)
                module.on_signal(signal.SIGTERM, frame)

        sys.setprofile(nest)
        try:
            with self.assertRaises(KeyboardInterrupt):
                module.on_signal(signal.SIGINT, None)
        finally:
            sys.setprofile(None)
        self.assertEqual([signal.SIGINT], module.received)


