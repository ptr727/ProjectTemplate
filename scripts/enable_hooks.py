#!/usr/bin/env python3
"""Enable a clone's Git hook framework, once per clone, the same way on Linux, macOS, and Windows.

The framework is read from the clone's top level. `.husky/` with a .NET tool manifest declaring
Husky.Net runs `dotnet tool restore`, then `dotnet husky install`. `.husky/` without one sets
`core.hooksPath` to `.husky`. `.pre-commit-config.yaml` runs `pre-commit install`. Both, or
neither, is a refusal.

A clone already enabled is reported and left as it is, so an unchanged run writes nothing. A
hooks setting, or a hook, that this framework did not write is never replaced. Installing over it
would change or chain the hook every checkout of the clone runs.

A linked worktree is refused before anything else is read. Its Git config is the base clone's, and
so is its hooks directory where no `core.hooksPath` is set, so a change there reaches every
checkout. It is told apart by `git rev-parse --git-dir` differing from `--git-common-dir`.

Exit 0 means enabled or already enabled, 1 a refusal or a failed step, and 2 an unknown argument.
On SIGINT or SIGTERM it stops the step it started and re-raises the signal.
"""

import argparse
import contextlib
import json
import os
import shutil
import signal
import subprocess
import sys
from pathlib import Path
from types import FrameType

PROG = "enable_hooks"
HUSKY_DIR = ".husky"
HUSKY_RUNTIME = (HUSKY_DIR, "_", "husky.sh")
PRE_COMMIT_CONFIG = ".pre-commit-config.yaml"
PRE_COMMIT_HEADER = b"# File generated by pre-commit"
TOOL_MANIFESTS = (".config/dotnet-tools.json", "dotnet-tools.json")
STOP_SECONDS = 10

DESCRIPTION = """\
Enable the Git hook framework of the clone holding the current directory, once per clone.
Run it from the clone itself: the maintainer's own checkout, an agent's standalone clone, or the
base clone a linked worktree is created from. A linked worktree is refused, since its Git config
is the base clone's. A worktree's own hook runtime, such as Husky.Net's .husky/_/husky.sh, is
prepared per repo-worktree "Preparing Git Hooks" instead.

The framework is read from the clone's top level:
  .husky/ and a .NET tool manifest declaring Husky.Net: dotnet tool restore, dotnet husky install
  .husky/ alone: git config core.hooksPath .husky
  .pre-commit-config.yaml: pre-commit install, after uv tool install pre-commit once per host

It reports what it found and what it changed. A clone already enabled is left as it is, and a
hooks setting or a hook the framework did not write is never replaced.

From a repository carrying hub_fetch_run.py, run: python3 hub_fetch_run.py scripts/enable_hooks.py

Exit status: 0 enabled or already enabled, 1 a refusal or a failed step, 2 an unknown argument."""


class Refusal(Exception):
    """A state this script leaves alone, or a step that failed, with the reason as its message."""


def say(message: str) -> None:
    print(f"{PROG}: {message}", flush=True)


def tool(name: str, remedy: str) -> str:
    """The full path of `name` on PATH, so a Windows `.cmd` or `.exe` resolves like a POSIX one."""
    path = shutil.which(name)
    if path is None:
        raise Refusal(f"{name} is not on PATH, so nothing was changed. {remedy}")
    return path


def git(git_exe: str, top: Path, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [git_exe, "-C", str(top), *args],
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=False,
    )


def locate(git_exe: str) -> Path:
    """The top level of the clone holding the current directory, refusing a linked worktree.

    `--path-format=absolute` would need Git 2.31, so `--git-common-dir` is joined onto the current
    directory instead, which leaves an absolute answer unchanged.
    """
    result = subprocess.run(
        [git_exe, "rev-parse", "--show-toplevel", "--absolute-git-dir", "--git-common-dir"],
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=False,
    )
    lines = result.stdout.splitlines()
    if result.returncode != 0 or len(lines) != 3:
        raise Refusal(f"found no Git work tree here: {result.stderr.strip() or result.stdout}")
    top, git_dir = Path(lines[0]), Path(lines[1])
    common_dir = Path.cwd() / lines[2]
    if git_dir.resolve() != common_dir.resolve():
        raise Refusal(
            f"{top} is a linked worktree. Its Git config is shared with the clone whose Git"
            f" directory is {common_dir}, so nothing was changed. Enable the hooks from that"
            " clone. This worktree's own hook runtime, such as Husky.Net's .husky/_/husky.sh,"
            ' is prepared per repo-worktree "Preparing Git Hooks".'
        )
    return top


def hooks_path(git_exe: str, top: Path) -> str | None:
    """The effective `core.hooksPath`, from any config scope, or None where it is unset."""
    result = git(git_exe, top, "config", "--type=path", "--get", "core.hooksPath")
    if result.returncode == 1 and not result.stderr.strip():
        return None
    if result.returncode != 0:
        raise Refusal(f"could not read core.hooksPath: {result.stderr.strip()}")
    return result.stdout.strip()


def names_husky(top: Path, value: str) -> bool:
    """Whether a `core.hooksPath` value names `.husky`, however it is spelled."""
    return (top / value).resolve() == (top / HUSKY_DIR).resolve()


def declares_husky_net(top: Path) -> bool:
    for relative in TOOL_MANIFESTS:
        manifest = top / relative
        if not manifest.is_file():
            continue
        try:
            data = json.loads(manifest.read_text(encoding="utf-8-sig"))
        except (OSError, ValueError) as exc:
            raise Refusal(f"could not read {relative}: {exc}") from exc
        if any(name.lower() == "husky" for name in data.get("tools", {})):
            return True
    return False


def run_step(command: list[str], label: str, top: Path) -> None:
    """Run one framework command from the top level, stopping it if this script is interrupted."""
    say(f"running {label}.")
    try:
        child = subprocess.Popen(command, cwd=top)
    except OSError as exc:
        raise Refusal(f"could not run {label}: {exc}") from exc
    try:
        status = child.wait()
    finally:
        if child.poll() is None:
            child.terminate()
            try:
                child.wait(timeout=STOP_SECONDS)
            except subprocess.TimeoutExpired:
                child.kill()
                child.wait()
    if status != 0:
        raise Refusal(f"{label} exited {status}. Re-run this script once that is fixed.")


def refuse_other_hooks_path(value: str) -> Refusal:
    return Refusal(
        f"core.hooksPath reads {value!r} rather than {HUSKY_DIR}, so nothing was changed. This"
        " script never replaces a hooks setting. Change it by hand if .husky is meant to run."
    )


def enable_husky(git_exe: str, top: Path) -> None:
    current = hooks_path(git_exe, top)
    if current is not None:
        if not names_husky(top, current):
            raise refuse_other_hooks_path(current)
        say(f"unchanged: core.hooksPath already reads {current}.")
        return
    result = git(git_exe, top, "config", "core.hooksPath", HUSKY_DIR)
    if result.returncode != 0:
        raise Refusal(f"could not set core.hooksPath: {result.stderr.strip()}")
    say(f"changed: set core.hooksPath to {HUSKY_DIR}.")


def enable_husky_net(git_exe: str, top: Path) -> None:
    current = hooks_path(git_exe, top)
    if current is not None and not names_husky(top, current):
        raise refuse_other_hooks_path(current)
    runtime = top.joinpath(*HUSKY_RUNTIME)
    if current is not None and runtime.is_file():
        say(f"unchanged: core.hooksPath already reads {current}, and {runtime} exists.")
        return
    dotnet = tool("dotnet", "Install the .NET SDK the repository builds with, then re-run this.")
    run_step([dotnet, "tool", "restore"], "dotnet tool restore", top)
    run_step([dotnet, "husky", "install"], "dotnet husky install", top)
    after = hooks_path(git_exe, top)
    if after is None or not names_husky(top, after) or not runtime.is_file():
        raise Refusal(
            f"dotnet husky install exited 0 but left core.hooksPath reading {after!r} and"
            f" {runtime} {'present' if runtime.is_file() else 'missing'}."
        )
    say(f"changed: core.hooksPath reads {after}, and {runtime} exists.")


def carries_pre_commit_header(hook: Path) -> bool:
    """Whether a line of `hook` opens on the pre-commit framework's own header."""
    return any(line.startswith(PRE_COMMIT_HEADER) for line in hook.read_bytes().splitlines())


def generated_by_pre_commit(hook: Path) -> bool:
    """Whether `hook` is an executable carrying the pre-commit framework's own header."""
    return hook.is_file() and os.access(hook, os.X_OK) and carries_pre_commit_header(hook)


def enable_pre_commit(git_exe: str, top: Path) -> None:
    current = hooks_path(git_exe, top)
    if current is not None:
        raise Refusal(
            f"core.hooksPath reads {current!r}, and pre-commit installs no hook while it is set,"
            " so nothing was changed. Unset it by hand if pre-commit is meant to run."
        )
    result = git(git_exe, top, "rev-parse", "--git-path", "hooks")
    if result.returncode != 0:
        raise Refusal(f"could not find the hooks directory: {result.stderr.strip()}")
    hook = top / result.stdout.strip() / "pre-commit"
    if generated_by_pre_commit(hook):
        say(f"unchanged: {hook} is already pre-commit's own hook.")
        return
    if hook.exists() and not carries_pre_commit_header(hook):
        raise Refusal(
            f"{hook} is a hook pre-commit did not write, and pre-commit install would move it"
            " aside and chain to it, so nothing was changed. Move it by hand if pre-commit is"
            " meant to run."
        )
    pre_commit = tool(
        "pre-commit",
        "Install it once per host with `uv tool install pre-commit`. Where it is still not"
        " found, run `uv tool update-shell` and restart the shell.",
    )
    run_step([pre_commit, "install"], "pre-commit install", top)
    if not generated_by_pre_commit(hook):
        raise Refusal(f"pre-commit install exited 0 but left no hook of its own at {hook}.")
    say(f"changed: {hook} is now pre-commit's own hook.")


def enable(git_exe: str, top: Path) -> None:
    has_husky = (top / HUSKY_DIR).is_dir()
    has_pre_commit = (top / PRE_COMMIT_CONFIG).is_file()
    if has_husky and has_pre_commit:
        raise Refusal(
            f"found both {HUSKY_DIR}/ and {PRE_COMMIT_CONFIG}, so which one this clone runs is"
            " unclear, and nothing was changed."
        )
    if has_pre_commit:
        say(f"found {PRE_COMMIT_CONFIG}, for the pre-commit framework.")
        enable_pre_commit(git_exe, top)
    elif has_husky and declares_husky_net(top):
        say(f"found {HUSKY_DIR}/ and a .NET tool manifest declaring Husky.Net.")
        enable_husky_net(git_exe, top)
    elif has_husky:
        say(f"found {HUSKY_DIR}/ with no Husky.Net tool manifest, so Git runs it directly.")
        enable_husky(git_exe, top)
    else:
        raise Refusal(
            f"found neither {HUSKY_DIR}/ nor {PRE_COMMIT_CONFIG} at {top}, so there is no hook"
            " to enable."
        )


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(
        prog="enable_hooks.py",
        description=DESCRIPTION,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.parse_args(argv)
    try:
        git_exe = tool("git", "Install Git, then re-run this.")
        top = locate(git_exe)
        say(f"clone {top}")
        enable(git_exe, top)
    except Refusal as exc:
        print(f"{PROG}: {exc}", file=sys.stderr)
        return 1
    return 0


received: list[int] = []


def on_signal(signum: int, frame: FrameType | None) -> None:
    """Record the signal and raise KeyboardInterrupt, so both signals unwind one path.

    A later signal is passed over, since it would cut the unwinding short.
    A later signal's handler can start inside this one, so a call from this frame returns too.
    """
    if received or (frame is not None and frame.f_code is on_signal.__code__):
        return
    received.append(signum)
    raise KeyboardInterrupt


def run(argv: list[str]) -> int | signal.Signals:
    """Run main, returning its status, or the signal that interrupted it once its cleanup ran.

    A SIGINT inherited as ignored, as a background child's is, stays ignored.
    """
    signal.signal(signal.SIGTERM, on_signal)
    if signal.getsignal(signal.SIGINT) is signal.default_int_handler:
        signal.signal(signal.SIGINT, on_signal)
    try:
        return main(argv)
    except KeyboardInterrupt:
        signum = signal.Signals(received[-1] if received else signal.SIGINT)
        print(f"{PROG}: interrupted by {signum.name}.", file=sys.stderr)
        return signum


def reraise(signum: signal.Signals) -> None:
    """End this process by `signum`, so a caller sees the signal rather than an exit status."""
    with contextlib.suppress(OSError):
        sys.stdout.flush()
        sys.stderr.flush()
    if sys.platform == "win32":
        sys.exit(130)
    signal.signal(signum, signal.SIG_DFL)
    os.kill(os.getpid(), signum)
    sys.exit(128 + signum)


if __name__ == "__main__":
    status = run(sys.argv[1:])
    if isinstance(status, signal.Signals):
        reraise(status)
    sys.exit(status)
